/**
 * @file lz_target.h
 * @brief 视觉层与规划层之间的**唯一契约**。
 *
 * 这个结构体是整个工程最关键的接缝：一边是视觉（"画面里的杆在哪"），
 * 一边是规划（"圆怎么画、往哪飞"）。它只描述**几何事实**，不含任何
 * 视觉库或 PSDK 类型，因此两件事同时成立：
 *
 *   1. 换视觉算法（HSV 阈值 → 模板匹配 → 深度学习）不必动规划器一行
 *   2. 规划器能用**手写死的**目标数组跑回归测试，不必有图、不必有飞机
 *
 * 本项目的目标固定为**杆状物（国旗杆）**，绕飞需要的几何量只有三个：
 * 杆在哪（WGS84）、杆多高、杆多粗。所以结构体就只装这三个。
 */

#ifndef LZ_TARGET_H
#define LZ_TARGET_H

#include "lz_types.h"

/**
 * 目标在画面中的像素位置（归一化到 [0,1]，与分辨率解耦）
 *
 * ## 命名约定（**每个字段都写明"是哪个点"**）
 *
 * 画面坐标：`u` 向右为正（0 = 左边缘），`v` 向下为正（0 = 上边缘）。
 * 云台俯仰向下为负 —— 所以 `v` 大 = 目标在画面偏下 = 光轴偏高了 = 要下压。
 *
 * ```
 *        u=0                     u=0.5                    u=1
 *  v=0   ┌───────────────────────┬───────────────────────┐
 *        │                       │                       │
 *        │        ┌──────────────┼──────────────┐        │  ← topV（旗面顶边）
 *        │        │              │              │        │
 *  v=0.5  │        │              ┼ ← 画面中心    │        │
 *        │        │              │   (0.5, 0.5)  │        │
 *        │        │              │              │        │
 *        │        └──────────────┼──────────────┘        │  ← bottomV（旗面底边）
 *  v=1   └───────────────────────┴───────────────────────┘
 *                    ↑
 *                  u（**杆列**，不是旗面中心 —— 见下）
 * ```
 *
 * ⚠️ **`u` 是"杆那一条竖线所在的列"，不是旗面外接框的中心。**
 * 实测两者相差 −3.7% ~ +4.1% 画面宽，且**符号随风向翻转**（风把旗吹向
 * 一侧时杆在另一侧）—— 所以那不是常数偏差，标定不掉。详见 `lz_vision.h`。
 * 对齐要对的是**杆**：激光打的是杆，且杆是竖直的，打在杆上任何一点
 * 反算出的经纬度都一样。
 *
 * ⚠️ **`topV` / `bottomV` 目前是"旗面外接框"的上下边**，不是杆的上下端
 * （杆比旗长得多）。它们只作调试与估高用。**杆的上下端还没标定** ——
 * 那需要现场杆的近景照片，见 lz/doc/VISION.md「步骤 3」。
 *
 * ⚠️ **本结构体里没有"瞄准点"这个字段**。瞄准点是上层算的
 * （`lz_align_target_v()`），目前取旗面框中点 —— 那是个**已知会偏的
 * 降级方案**（现场"旗在杆顶"，旗中点比杆中点高 6.75 m，12.5 m 外约 28°）。
 * 等杆端点标定好之后，只改那一个函数。
 */
typedef struct {
    double u;          /*!< **杆列**的归一化横坐标 [0,1]，0 = 左边缘 */
    double v;          /*!< **旗面外接框底边**的归一化纵坐标 [0,1]，0 = 上边缘。
                        *   ⚠️ 名字里的 `v` 只说"纵向"，**不说明是哪个点** ——
                        *   这是它唯一的使用者（黄金值测试与探针）需要知道的。
                        *   权威的"旗面上下边"是下面的 `topV`/`bottomV`。 */
    double topV;       /*!< **旗面外接框顶边**的归一化纵坐标 [0,1] */
    double bottomV;    /*!< **旗面外接框底边**的归一化纵坐标 [0,1]。
                        *   恰好与 `v` 相等 —— 保留两个名字是因为 `v` 被
                        *   黄金值测试当作"框底"用，而 `bottomV` 是语义名。 */
} LzPixelBox;

/** 一根杆（国旗杆） */
typedef struct {
    int id;                /*!< 目标编号，由视觉层分配，同一目标跨帧应一致 */
    LzGeo geo;             /*!< 杆底的 WGS84 位置 —— 视觉 + 机载定位解算得出 */
    double heightM;        /*!< 杆高 m，从杆底到杆顶。<= 0 表示未知 */
    double radiusM;        /*!< 杆半径 m。<= 0 表示未知；绕飞取中心，此值仅用于避让 */
    LzPixelBox pixel;      /*!< 像素位置，主要用于调试与跨帧关联 */
    double confidence;     /*!< 置信度 [0,1]；低于阈值的不应出现在列表里 */
} LzTarget;

/** 目标列表 */
typedef struct {
    LzTarget *items;
    size_t count;
    size_t capacity;
} LzTargetList;

void LzTargetList_Init(LzTargetList *list);
LzStatus LzTargetList_Push(LzTargetList *list, const LzTarget *target);
void LzTargetList_Free(LzTargetList *list);

/** @brief 目标是否可用于规划（位置合法、置信度达标） */
bool LzTarget_IsUsable(const LzTarget *target, double minConfidence);

#endif /* LZ_TARGET_H */
