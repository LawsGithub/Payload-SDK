/**
 * @file lz_visual_align.h
 * @brief 视觉照准：看画面 → 算出偏差 → 转云台，反复逼近到目标居中。
 *
 * ## 这是"视觉闭环"的落点
 *
 * 在此之前三个环节都已单独验过，但从未连起来：
 *
 * | 环节 | 在哪验的 |
 * |---|---|
 * | 取图（1440x1080 @30fps 广角 RGB） | `lz_liveview_probe` |
 * | 检测 + 算 Δθ | `lz_vision_probe`（真机 40/40 命中、置信度 0.93） |
 * | 转云台（绝对角到位、误差 0.00°、能读回） | `lz_gimbal_probe` |
 *
 * 本模块把它们串成**一个可被操作员触发的动作**。
 *
 * ## 为什么是"闭环迭代"而不是"一次算到位"
 *
 * 几何上，高度定 + 半径定 ⇒ 俯仰角恒定 ⇒ 一次算准就够了。但那个"一次算准"
 * 依赖一串假设（相机没有安装偏角、画面中心就是光轴中心、云台按指令准确执行）。
 * **实测已经推翻过其中一条**：云台到位精度确实好（误差 0.00°），
 * 但相机-云台的光轴关系没有单独标定过。
 *
 * 迭代把这一串假设**换成一次实测**：转完再拍一帧看目标动没动，
 * 动到哪了继续修。收敛判据是"连续两轮都在死区里"，不是"算出来落在死区里"。
 *
 * ## ⚠️ 瞄准点目前是"旗面框中心"，不是"杆的中点"
 *
 * 要"杆的中点"得知道杆的上下端（`lz_pole_extent`），而它**在现有测试数据上
 * 验证不了**（2026-10-06 复核措辞：不是"没验过"，是"验不了" ——
 * 现有 6 张测试图的裁剪窗口恰好等于整幅图，量到的是图边而不是杆端。
 * 在拿到现场杆的近景照片之前，旗面中心是**唯一有依据**的选择。
 *
 * ⇒ **这是降级方案，会瞄偏**：现场是"旗在杆顶"，旗中点比杆中点高，
 *   12.5 m 外差约 28°。**所以本模块必须在浮窗与日志里显式说明这一点，
 *   不能静默降级。** 等步骤 3 做完，改 `lz_align_target_v()` 一个函数即可。
 */

#ifndef LZ_VISUAL_ALIGN_H
#define LZ_VISUAL_ALIGN_H

#include <stdbool.h>

#include "lz_types.h"

/** 照准过程的阶段（供浮窗/日志用） */
typedef enum {
    LZ_ALIGN_IDLE = 0,
    LZ_ALIGN_RUNNING,      /*!< 正在迭代 */
    LZ_ALIGN_DONE,         /*!< 已对准（收敛） */
    LZ_ALIGN_FAILED,       /*!< 失败（未收敛/起飞失败/云台被拒） */
} LzAlignState;

/**
 * @brief 处理"识别目标"按钮：开始或停止照准
 *
 * ⚠️ 与两个记录按钮同一个模式：**控件回调只置标志，本函数由主循环调用**。
 * 但本函数内部**不做**耗时动作（开图/转云台），它只切状态 ——
 * 真正的迭代在 `LzVisualAlign_Tick()` 里，每拍推进一小步。
 *
 * 这样设计的理由：一次完整的照准要十几秒（多轮 × 每轮约 1.5 s 等云台），
 * 而主循环是 100 ms 一拍。把十几秒塞进一拍会把整个状态机卡住，
 * 操作员这期间拨开关都没有响应。**分解成"每拍推进一小步"。**
 */
void LzVisualAlign_RequestToggle(void);

/** @brief 当前状态（供浮窗与外部查询） */
LzAlignState LzVisualAlign_State(void);

/**
 * @brief 主循环的一拍：推进照准流程
 *
 * 内部维护一个"每拍只做一件事"的小状态机：
 * `IDLE → 初始化(开图+云台) → 等云台角 → 取帧 → 检测 → 算Δθ → 转云台 → 等 → 取帧 …`
 *
 * ⚠️ **判据不在本模块，在 `lz_core` 的 `lz_align.c`** —— 那里是零依赖纯函数，
 * `tests/lz_test_align.c` 用 102 项断言守着它。本文件只做"接 PSDK 的活"。
 * 这么分的理由：`app/` 依赖 PSDK ⇒ 桌面上编不了也测不了 ⇒ 写在这里的判据
 * 等于没有测试（与 `LzPlan_ClampWaypointCount()` 被抽出去同一个理由）。
 *
 * 必须在 `LzCore` 起来之后（要用取图与云台接口），建议与
 * `LzMission_Tick()` 同处调用。
 */
void LzVisualAlign_Tick(void);

/** @brief 释放资源（停止取图、关云台模块）。进程退出前调用。 */
void LzVisualAlign_DeInit(void);

#endif /* LZ_VISUAL_ALIGN_H */
